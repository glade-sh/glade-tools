func TestGenerateVersionTables(t *testing.T) {
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module github.com/glade-sh/glade\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	row := func(id, product, kind, namespace, typeName, memberName string) surfaceledger.SurfaceLedgerRow {
		return surfaceledger.SurfaceLedgerRow{SurfaceID: id, Product: product, Kind: kind, Namespace: namespace, TypeName: typeName, MemberName: memberName}
	}
	change := func(kind surfaceledger.DeltaKind, r surfaceledger.SurfaceLedgerRow) SurfaceChange {
		entry := surfaceledger.DeltaEntry{SurfaceID: r.SurfaceID, Kind: kind}
		if kind == surfaceledger.DeltaRemoved {
			entry.Old = &r
		} else {
			entry.New = &r
		}
		return SurfaceChange{Entry: entry}
	}
	unsupported := change(surfaceledger.DeltaAdded, row("apex:System.Preview", surfaceledger.ProductApex, surfaceledger.KindType, "System", "Preview", ""))
	unsupported.Classification = &surfaceledger.ReleaseClassification{
		SurfaceID:   "apex:System.Preview",
		Scope:       surfaceledger.ScopeOutsideClaim,
		Disposition: surfaceledger.DispoExplicitUnsupported,
		ReasonRef:   "preview",
	}
	analysis := Analysis{
		Contract: Contract{
			Defaults: Defaults{Source: "65.0", Endpoint: "65.0"},
			Windows: Windows{
				Source:   []VersionProof{{Version: "65.0"}, {Version: "66.0"}, {Version: "67.0"}},
				Endpoint: []VersionProof{{Version: "60.0"}, {Version: "65.0"}, {Version: "66.0"}, {Version: "67.0"}},
			},
			Behaviors: []Behavior{{ID: "manual", SurfaceIDs: []string{"apex:Foo.NewType.changed()"}}, {ID: "preview", Outcome: "explicit-non-parity", SurfaceIDs: []string{"apex:System.Preview"}}},
		},
		Report: Report{
			SurfaceDelta:    Denominator{Total: 9, Classified: 9},
			BehaviorDelta:   Denominator{Total: 1, Classified: 1},
			ChangeInventory: ChangeInventoryDenominator{Total: 1, Routed: 1},
			Ranges: map[string]Range{
				"apex:foo.stable":                  {Since: 65},
				"apex:foo.newtype":                 {Since: 66},
				"apex:foo.newtype.value":           {Since: 67},
				"apex:foo.newtype.old()":           {Since: 65, Until: 67},
				"apex:foo.newtype.run(string)":     {Since: 66},
				"apex:foo.newtype.run(integer)":    {Since: 67},
				"apex:foo.newtype.changed()":       {Since: 65},
				"lwc:`experience/blockBuilderApi`": {Since: 66},
				"tooling:NewObject":                {Since: 67},
				"apex:system.preview":              {Since: 67},
			},
		},
		SurfaceChanges: []SurfaceChange{
			change(surfaceledger.DeltaAdded, row("apex:Foo.NewType", surfaceledger.ProductApex, surfaceledger.KindType, "Foo", "NewType", "")),
			change(surfaceledger.DeltaAdded, row("apex:Foo.NewType.value", surfaceledger.ProductApex, surfaceledger.KindProperty, "Foo", "NewType", "value")),
			change(surfaceledger.DeltaRemoved, row("apex:Foo.NewType.old()", surfaceledger.ProductApex, surfaceledger.KindMethod, "Foo", "NewType", "old")),
			change(surfaceledger.DeltaAdded, row("apex:Foo.NewType.run(String)", surfaceledger.ProductApex, surfaceledger.KindMethod, "Foo", "NewType", "run")),
			change(surfaceledger.DeltaAdded, row("apex:Foo.NewType.run(Integer)", surfaceledger.ProductApex, surfaceledger.KindMethod, "Foo", "NewType", "run")),
			change(surfaceledger.DeltaChanged, row("apex:Foo.NewType.changed()", surfaceledger.ProductApex, surfaceledger.KindMethod, "Foo", "NewType", "changed")),
			change(surfaceledger.DeltaAdded, row("lwc:`experience/blockBuilderApi`", surfaceledger.ProductLWC, surfaceledger.KindModule, "", "", "")),
			change(surfaceledger.DeltaAdded, row("tooling:NewObject", surfaceledger.ProductTooling, surfaceledger.KindType, "", "", "")),
			unsupported,
		},
	}

	paths, err := Generate(analysis, root, true)
	if err != nil {
		t.Fatalf("Generate write: %v", err)
	}
	if len(paths) != 5 {
		t.Fatalf("generated paths = %v", paths)
	}
	want := map[string]string{
		"internal/apexversion/support_generated.go": `// Code generated by glade-tools salesforce release; DO NOT EDIT.

package apexversion

const DefaultSourceAPIVersion = "65.0"

var SupportedSourceAPIVersions = []string{"65.0", "66.0", "67.0"}
`,
		"internal/storage/rest_versions_generated.go": `// Code generated by glade-tools salesforce release; DO NOT EDIT.

package storage

const DefaultRESTAPIVersion = "65.0"

var SupportedRESTAPIVersions = []string{"60.0", "65.0", "66.0", "67.0"}
`,
		"internal/server/tooling_availability_generated.go": `// Code generated by glade-tools salesforce release; DO NOT EDIT.

package server

import "github.com/glade-sh/glade/internal/apexversion"

var generatedToolingObjectAvailability = map[string]apexversion.Range{
	"NewObject": {Since: 67},
}
`,
		"internal/sema/platform_availability_generated.go": `// Code generated by glade-tools salesforce release; DO NOT EDIT.

package sema

import "github.com/glade-sh/glade/internal/apexversion"

var generatedPlatformTypeAvailability = map[string]apexversion.Range{
	"foo.newtype": {Since: 66},
}
var generatedPlatformMemberAvailability = map[string]apexversion.Range{
	"foo.newtype.old": {Since: 65, Until: 67},
	"foo.newtype.value": {Since: 67},
}
var generatedPlatformExactAvailability = map[string]apexversion.Range{
	"apex:foo.newtype.old()": {Since: 65, Until: 67},
	"apex:foo.newtype.run(integer)": {Since: 67},
	"apex:foo.newtype.run(string)": {Since: 66},
	"apex:foo.newtype.value": {Since: 67},
}
var generatedManualSurfaceIDs = []string{"apex:foo.newtype.changed()"}
var generatedUnsupportedPlatformSurfaceIDs = []string{"apex:system.preview"}
`,
		"internal/lwc/compile/module_availability_generated.go": `// Code generated by glade-tools salesforce release; DO NOT EDIT.

package compile

import "github.com/glade-sh/glade/internal/apexversion"

var generatedLWCModuleAvailability = map[string]apexversion.Range{
	"experience/blockBuilderApi": {Since: 66},
}
`,
	}
	for path, source := range want {
		formatted, err := format.Source([]byte(source))
		if err != nil {
			t.Fatalf("format expected %s: %v", path, err)
		}
		got, err := os.ReadFile(filepath.Join(root, path))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != string(formatted) {
			t.Fatalf("%s:\n%s\nwant:\n%s", path, got, formatted)
		}
	}
	if _, err := Generate(analysis, root, false); err != nil {
		t.Fatalf("Generate check: %v", err)
	}
	if err := os.WriteFile(filepath.Join(root, "internal/apexversion/support_generated.go"), []byte("drift\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := Generate(analysis, root, false); err == nil {
		t.Fatal("Generate check unexpectedly accepted drift")
	}
}

func TestDocumentationOnlyDeltaDoesNotCreateRuntimeAvailability(t *testing.T) {
	row := func(id, typ, member string) surfaceledger.SurfaceLedgerRow {
		kind := surfaceledger.KindType
		if member != "" {
			kind = surfaceledger.KindMethod
		}
		return surfaceledger.SurfaceLedgerRow{SurfaceID: id, Product: surfaceledger.ProductApex, Kind: kind, Namespace: "System", TypeName: typ, MemberName: member}
	}
	old := row("apex:System.Existing", "Existing", "")
	added := row("apex:System.Documented", "Documented", "")
	changed := row("apex:System.Existing.other()", "Existing", "other")
	overload := row("apex:System.Existing.run(String)", "Existing", "run")
	newOverload := row("apex:System.Existing.run(Integer)", "Existing", "run")
	unsupported := func(id string) *surfaceledger.ReleaseClassification {
		return &surfaceledger.ReleaseClassification{SurfaceID: id, Scope: surfaceledger.ScopeOutsideClaim, Disposition: surfaceledger.DispoExplicitUnsupported, ReasonRef: "documentation-only"}
	}
	a := Analysis{
		Contract: Contract{Defaults: Defaults{Source: "65.0", Endpoint: "65.0"}, Windows: Windows{Source: []VersionProof{{Version: "65.0"}, {Version: "66.0"}, {Version: "67.0"}, {Version: "68.0"}}}, Releases: []Release{{Name: "Old", APIVersion: "66.0"}, {Name: "New", APIVersion: "68.0"}}},
		Report:   Report{Ranges: map[string]Range{"apex:system.existing": {Since: 66, Until: 68}, "apex:system.documented": {Since: 68}, "apex:system.existing.other()": {Since: 65}, "apex:system.existing.run(string)": {Since: 66}, "apex:system.existing.run(integer)": {Since: 68}}},
		SurfaceChanges: []SurfaceChange{
			{CurrentRelease: "Old", Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaAdded, SurfaceID: old.SurfaceID, New: &old}},
			{CurrentRelease: "New", Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaRemoved, SurfaceID: old.SurfaceID, Old: &old}, Classification: unsupported(old.SurfaceID)},
			{CurrentRelease: "New", Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaAdded, SurfaceID: added.SurfaceID, New: &added}, Classification: unsupported(added.SurfaceID)},
			{CurrentRelease: "New", Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaChanged, SurfaceID: changed.SurfaceID, New: &changed}, Classification: unsupported(changed.SurfaceID)},
			{CurrentRelease: "Old", Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaAdded, SurfaceID: overload.SurfaceID, New: &overload}},
			{CurrentRelease: "New", Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaAdded, SurfaceID: newOverload.SurfaceID, New: &newOverload}, Classification: unsupported(newOverload.SurfaceID)},
		},
	}
	generated, err := renderGeneratedVersionSources(a)
	if err != nil {
		t.Fatal(err)
	}
	source := string(generated["internal/sema/platform_availability_generated.go"])
	for _, bad := range []string{"system.documented", "Until: 68", "existing.other()", "run(integer)"} {
		if strings.Contains(source, bad) {
			t.Fatalf("documentation-only delta emitted %q:\n%s", bad, source)
		}
	}
	for _, want := range []string{`"system.existing": {Since: 66}`, `"system.existing.run": {Since: 66}`, `generatedUnsupportedPlatformSurfaceIDs = []string{}`} {
		if !strings.Contains(source, want) {
			t.Fatalf("missing preserved %q:\n%s", want, source)
		}
	}
}

func TestRuntimeUnsupportedRequiresExplicitBehaviorBinding(t *testing.T) {
	row := surfaceledger.SurfaceLedgerRow{SurfaceID: "apex:System.New", Product: surfaceledger.ProductApex, Kind: surfaceledger.KindType, Namespace: "System", TypeName: "New"}
	change := SurfaceChange{Entry: surfaceledger.DeltaEntry{Kind: surfaceledger.DeltaAdded, SurfaceID: row.SurfaceID, New: &row}, Classification: &surfaceledger.ReleaseClassification{SurfaceID: row.SurfaceID, Scope: surfaceledger.ScopeT0, Disposition: surfaceledger.DispoExplicitUnsupported, ReasonRef: "unsupported"}}
	a := Analysis{SurfaceChanges: []SurfaceChange{change}}
	if _, err := renderGeneratedVersionSources(a); err == nil || !strings.Contains(err.Error(), "explicit-non-parity behavior") {
		t.Fatalf("unbound runtime gate: %v", err)
	}
}
